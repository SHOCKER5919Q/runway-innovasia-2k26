#!/usr/bin/env python3
"""Reproduce every accuracy figure RUNWAY publishes.

    python scripts/evaluate_models.py --date 2026-11-07

Writes docs/EVALUATION_RESULTS.md and prints a summary. Nothing in the
product quotes an accuracy number that this script cannot regenerate.
"""
from __future__ import annotations

import argparse
import json
import sys
from datetime import date
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "backend"))

from sqlalchemy import select  # noqa: E402

from app.core.db import SessionLocal  # noqa: E402
from app.core.money import format_inr  # noqa: E402
from app.financial_states.state_manager import reconcile_forecasts  # noqa: E402
from app.forecast.payment_delay import train  # noqa: E402
from app.models import Business, Invoice  # noqa: E402


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--date", default=None)
    ap.add_argument("--out", default=str(ROOT / "docs" / "EVALUATION_RESULTS.md"))
    a = ap.parse_args()
    as_of = date.fromisoformat(a.date) if a.date else date.today()

    db = SessionLocal()
    lines = [
        "# Evaluation results",
        "",
        "> Generated by `scripts/evaluate_models.py`. Every figure here is measured on "
        "held-out data from the workspace's own ledger. Re-run the script to reproduce it.",
        "",
        f"**Evaluated as of:** {as_of.isoformat()}",
        "",
    ]
    summary = {}
    try:
        for biz in db.scalars(select(Business)).all():
            invoices = db.scalars(select(Invoice).where(Invoice.business_id == biz.id)).all()
            if not invoices:
                continue
            print(f"\n=== {biz.name} ===")
            lines += [f"## {biz.name}", "", f"_{biz.industry.replace('_', ' ')}, {biz.city}_", ""]

            m = train(invoices, as_of)
            mt = m.metrics
            lines += ["### Payment-delay model", "",
                      f"Model version `{mt.get('model_version')}` · split: {mt.get('split')}", ""]
            if mt.get("status") != "trained":
                lines += [f"Not trained: {mt.get('reason')}", ""]
                print("  payment-delay model: not trained -", mt.get("reason"))
            else:
                lines += [
                    "| Predictor | MAE (days) | RMSE | WAPE | Bias |",
                    "|---|---:|---:|---:|---:|",
                    _row("Shipped model", mt["model"]),
                    _row("Baseline: per-customer median", mt["baseline_customer_median"]),
                    _row("Baseline: global median", mt["baseline_global_median"]),
                    "",
                    f"- Train / test: {mt['n_train']} / {mt['n_test']} invoices, chronological.",
                    f"- Median estimator chosen: `{mt['median_estimator']}`, "
                    f"stacking weight on the GBM {mt['stacking_weight_on_gbm']}.",
                    f"- **Model selection:** {mt['model_selection']}",
                    f"- Interval calibration: raw P10–P90 coverage "
                    f"{mt['coverage_p10_p90_raw']:.1%} → conformal "
                    f"{mt['coverage_p10_p90_conformal']:.1%} against an "
                    f"{mt['coverage_target']:.0%} target "
                    f"(scale {mt['conformal_scale']}).",
                    f"- Pinball loss: P10 {mt['pinball_p10']}, P50 {mt['pinball_p50']}, "
                    f"P90 {mt['pinball_p90']}.",
                    f"- Operational alert (\"more than 15 days late\"): precision "
                    f"{mt['late_alert_precision_gt15d']}, recall {mt['late_alert_recall_gt15d']}.",
                    "",
                ]
                print(f"  payment-delay MAE {mt['model']['mae_days']}d vs baseline "
                      f"{mt['baseline_customer_median']['mae_days']}d; "
                      f"coverage {mt['coverage_p10_p90_conformal']:.0%}")
                print(f"  selection: {mt['model_selection']}")

            acc = reconcile_forecasts(db, biz.id, as_of)
            db.commit()
            lines += ["### Cash-forecast backtest", ""]
            if not acc["available"]:
                lines += [acc["note"], ""]
                print("  cash forecast: nothing has reached its target week yet")
            else:
                lines += ["| Horizon | n | MAE | RMSE | WAPE | Bias | P10–P90 coverage |",
                          "|---:|---:|---:|---:|---:|---:|---:|"]
                for h in acc["cash_forecast_by_horizon"]:
                    lines.append(
                        f"| {h['horizon_weeks']} wk | {h['n']} | {format_inr(h['mae_paise'])} | "
                        f"{format_inr(h['rmse_paise'])} | {h['wape']:.1%} | "
                        f"{format_inr(h['bias_paise'])} | {h['p10_p90_coverage']:.0%} |")
                lines += ["", f"Target coverage is 80%.", ""]
                if acc.get("payment_prediction_accuracy"):
                    pa = acc["payment_prediction_accuracy"]
                    lines += [
                        f"Realised payment-date predictions: **{pa['n']}** resolved, "
                        f"MAE **{pa['mae_days']} days**, bias {pa['bias_days']} days, "
                        f"P10–P90 coverage **{pa['p10_p90_coverage']:.0%}**.", ""]
                    print(f"  payment dates: n={pa['n']} MAE={pa['mae_days']}d "
                          f"coverage={pa['p10_p90_coverage']:.0%}")
                near = [h for h in acc["cash_forecast_by_horizon"] if h["horizon_weeks"] <= 4]
                if near:
                    cov = sum(h["p10_p90_coverage"] * h["n"] for h in near) / sum(h["n"] for h in near)
                    print(f"  cash forecast <=4wk coverage: {cov:.0%}")
            summary[biz.name] = {"payment_delay": mt, "cash_forecast": acc}

        lines += [
            "## How to read this",
            "",
            "- **WAPE** is the sum of absolute errors over the sum of actuals; it is used "
            "instead of MAPE because a cash position can approach zero, where MAPE explodes.",
            "- **Coverage** is the share of outcomes that fell inside the P10–P90 band. "
            "Below 80% the band is too narrow; well above it, too wide.",
            "- **Bias** is the mean signed error. A positive bias means RUNWAY predicted "
            "more cash than arrived.",
            "- Long-horizon rows are computed on very few observations and should not be "
            "read as a stable estimate. The row's `n` says how few.",
            "",
        ]
        Path(a.out).write_text("\n".join(lines) + "\n")
        print(f"\nWrote {a.out}")
    finally:
        db.close()
    return 0


def _row(label: str, s: dict) -> str:
    return (f"| {label} | {s['mae_days']} | {s['rmse_days']} | "
            f"{s['wape']:.1%} | {s['bias_days']} |")


if __name__ == "__main__":
    raise SystemExit(main())
